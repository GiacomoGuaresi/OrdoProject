//! Linux: Nautilus scripts and Dolphin service menus.

use std::path::{Path, PathBuf};

use super::{IntegrationItem, SORT_FLAG, menu_label, remove_path, shell_quote, write_file};
use crate::error::Result;
use crate::lang::Lang;

/// File managers found on the system.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Detected {
    pub nautilus: bool,
    pub dolphin: bool,
}

fn on_path(program: &str) -> bool {
    std::env::var_os("PATH")
        .is_some_and(|paths| std::env::split_paths(&paths).any(|dir| dir.join(program).is_file()))
}

/// Detects the supported file managers.
pub fn detect() -> Detected {
    Detected {
        nautilus: on_path("nautilus"),
        dolphin: on_path("dolphin"),
    }
}

/// Name of the Nautilus script (shown in the "Scripts" submenu); fixed so it
/// can be found again whatever the language.
pub const NAUTILUS_SCRIPT: &str = "Ordo";
pub const DOLPHIN_MENU: &str = "ordo-sort.desktop";

pub fn nautilus_path(home: &Path) -> PathBuf {
    home.join(".local/share/nautilus/scripts")
        .join(NAUTILUS_SCRIPT)
}

pub fn dolphin_path(home: &Path) -> PathBuf {
    home.join(".local/share/kio/servicemenus")
        .join(DOLPHIN_MENU)
}

pub fn status(home: &Path) -> Vec<IntegrationItem> {
    status_with(home, detect())
}

fn status_with(home: &Path, detected: Detected) -> Vec<IntegrationItem> {
    let nautilus = nautilus_path(home);
    let dolphin = dolphin_path(home);
    vec![
        IntegrationItem {
            id: "nautilus".into(),
            name: "Nautilus (GNOME Files)".into(),
            available: detected.nautilus,
            installed: nautilus.is_file(),
            location: nautilus.display().to_string(),
        },
        IntegrationItem {
            id: "dolphin".into(),
            name: "Dolphin (KDE)".into(),
            available: detected.dolphin,
            installed: dolphin.is_file(),
            location: dolphin.display().to_string(),
        },
    ]
}

/// Nautilus passes the selected local files as arguments; with nothing
/// selected the script sorts the current folder.
pub fn nautilus_script(app_exe: &Path) -> String {
    format!(
        "#!/bin/sh\n\
         # Sort with Ordo — generated by Ordo, removed from its settings.\n\
         [ \"$#\" -eq 0 ] && set -- \"$PWD\"\n\
         exec {exe} {SORT_FLAG} \"$@\"\n",
        exe = shell_quote(app_exe)
    )
}

fn desktop_exec_quote(path: &Path) -> String {
    // Desktop Entry spec: quote with double quotes, escape `"`, `` ` ``, `$` and `\`.
    let mut out = String::from("\"");
    for c in path.to_string_lossy().chars() {
        if matches!(c, '"' | '`' | '$' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

pub fn dolphin_service_menu(app_exe: &Path, lang: Lang) -> String {
    format!(
        "[Desktop Entry]\n\
         Type=Service\n\
         MimeType=all/allfiles;inode/directory;\n\
         X-KDE-ServiceTypes=KonqPopupMenu/Plugin\n\
         Actions=sortWithOrdo;\n\
         \n\
         [Desktop Action sortWithOrdo]\n\
         Name={label}\n\
         Icon=io.github.giacomoguaresi.ordo\n\
         Exec={exe} {SORT_FLAG} %F\n",
        label = menu_label(lang),
        exe = desktop_exec_quote(app_exe)
    )
}

/// Installs the integrations for the detected file managers.
pub fn install(home: &Path, app_exe: &Path, lang: Lang, detected: &Detected) -> Result<()> {
    if detected.nautilus {
        write_file(&nautilus_path(home), &nautilus_script(app_exe), true)?;
    }
    if detected.dolphin {
        // KDE 6 only runs service menus that are executable.
        write_file(
            &dolphin_path(home),
            &dolphin_service_menu(app_exe, lang),
            true,
        )?;
    }
    Ok(())
}

pub fn uninstall(home: &Path) -> Result<()> {
    remove_path(&nautilus_path(home))?;
    remove_path(&dolphin_path(home))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_files() {
        let exe = Path::new("/opt/Ordo $x/ordo");
        let script = nautilus_script(exe);
        assert!(script.starts_with("#!/bin/sh\n"));
        assert!(script.contains("exec '/opt/Ordo $x/ordo' --sort \"$@\""));
        let menu = dolphin_service_menu(exe, Lang::En);
        assert!(menu.contains("Name=Sort with Ordo"));
        assert!(menu.contains(r#"Exec="/opt/Ordo \$x/ordo" --sort %F"#));
    }

    #[test]
    fn installs_only_detected_file_managers() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path();
        let exe = Path::new("/usr/bin/ordo-app");
        let only_dolphin = Detected {
            nautilus: false,
            dolphin: true,
        };
        install(home, exe, Lang::It, &only_dolphin).unwrap();
        let s = status_with(home, only_dolphin);
        assert!(!s[0].installed);
        assert!(s[1].installed);
        assert!(
            std::fs::read_to_string(dolphin_path(home))
                .unwrap()
                .contains("Name=Ordina con Ordo")
        );
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(dolphin_path(home))
                .unwrap()
                .permissions()
                .mode();
            assert_eq!(mode & 0o111, 0o111);
        }

        install(
            home,
            exe,
            Lang::En,
            &Detected {
                nautilus: true,
                dolphin: true,
            },
        )
        .unwrap();
        assert!(nautilus_path(home).is_file());
        uninstall(home).unwrap();
        assert!(
            status_with(home, Detected::default())
                .iter()
                .all(|i| !i.installed)
        );
    }

    #[cfg(unix)]
    #[test]
    fn nautilus_script_runs() {
        // Use a fake "app" that prints its arguments.
        let tmp = tempfile::tempdir().unwrap();
        let fake = tmp.path().join("fake app");
        write_file(&fake, "#!/bin/sh\nprintf '%s\\n' \"$@\"\n", true).unwrap();
        let script = tmp.path().join("script");
        write_file(&script, &nautilus_script(&fake), true).unwrap();
        let out = std::process::Command::new(&script)
            .args(["/a b.txt", "/c.pdf"])
            .output()
            .unwrap();
        assert_eq!(
            String::from_utf8_lossy(&out.stdout),
            "--sort\n/a b.txt\n/c.pdf\n"
        );
        let out = std::process::Command::new(&script)
            .current_dir(tmp.path())
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert!(stdout.starts_with("--sort\n"));
        assert_eq!(stdout.lines().count(), 2, "sorts the current folder");
    }
}
