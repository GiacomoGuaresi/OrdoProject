//! The "Ordo" launcher: an entry in the system's app launcher (Launchpad /
//! Spotlight, Start menu, desktop app menus) that immediately sorts the
//! configured folders (`--quick-sort`). The full app is listed as
//! "Ordo - Settings".
//!
//! - macOS: a tiny app bundle `~/Applications/Ordo.app` whose executable is a
//!   shell script that starts the real app.
//! - Windows: a Start menu shortcut `Ordo.lnk`.
//! - Linux: a desktop entry in `~/.local/share/applications`.

use std::path::{Path, PathBuf};

use super::{IntegrationItem, remove_path, shell_quote, write_file};
use crate::error::Result;

/// Flag understood by the desktop app: sort the configured folders.
pub const QUICK_SORT_FLAG: &str = "--quick-sort";

/// Name shown in the launcher.
pub const LAUNCHER_NAME: &str = "Ordo";

const LAUNCHER_ID: &str = "io.github.giacomoguaresi.ordo.launcher";

// ---------------------------------------------------------------- macOS

pub fn macos_path(home: &Path) -> PathBuf {
    home.join("Applications")
        .join(format!("{LAUNCHER_NAME}.app"))
}

/// The `.app` bundle containing `exe`, if any.
fn enclosing_bundle(exe: &Path) -> Option<&Path> {
    exe.ancestors()
        .find(|p| p.extension().is_some_and(|e| e == "app"))
}

pub fn macos_script(app_exe: &Path) -> String {
    let start = match enclosing_bundle(app_exe) {
        // `open -n` starts a new process: it hands the request to a running
        // instance (if any) and exits.
        Some(bundle) => format!(
            "exec /usr/bin/open -n -a {} --args {QUICK_SORT_FLAG}",
            shell_quote(bundle)
        ),
        None => format!(
            "{} {QUICK_SORT_FLAG} >/dev/null 2>&1 &",
            shell_quote(app_exe)
        ),
    };
    format!("#!/bin/sh\n# Generated by Ordo.\n{start}\n")
}

fn macos_info_plist(has_icon: bool) -> String {
    let icon = if has_icon {
        "\t<key>CFBundleIconFile</key>\n\t<string>icon.icns</string>\n"
    } else {
        ""
    };
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDisplayName</key>
	<string>{LAUNCHER_NAME}</string>
	<key>CFBundleExecutable</key>
	<string>ordo-quick-sort</string>
{icon}	<key>CFBundleIdentifier</key>
	<string>{LAUNCHER_ID}</string>
	<key>CFBundleName</key>
	<string>{LAUNCHER_NAME}</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>{version}</string>
	<key>LSApplicationCategoryType</key>
	<string>public.app-category.utilities</string>
	<key>LSUIElement</key>
	<true/>
</dict>
</plist>
"#,
        version = crate::VERSION
    )
}

pub fn macos_install(home: &Path, app_exe: &Path) -> Result<()> {
    let bundle = macos_path(home);
    remove_path(&bundle)?;
    let contents = bundle.join("Contents");
    let icon = enclosing_bundle(app_exe).map(|b| b.join("Contents/Resources/icon.icns"));
    let has_icon = match icon {
        Some(src) if src.is_file() => {
            let dst = contents.join("Resources/icon.icns");
            std::fs::create_dir_all(dst.parent().expect("has parent"))
                .and_then(|_| std::fs::copy(&src, &dst))
                .is_ok()
        }
        _ => false,
    };
    write_file(
        &contents.join("Info.plist"),
        &macos_info_plist(has_icon),
        false,
    )?;
    write_file(
        &contents.join("MacOS/ordo-quick-sort"),
        &macos_script(app_exe),
        true,
    )
}

/// Makes Spotlight / Launchpad notice the new app right away.
fn register_with_launch_services(bundle: &Path) {
    #[cfg(target_os = "macos")]
    {
        let _ = std::process::Command::new(
            "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister",
        )
        .arg("-f")
        .arg(bundle)
        .status();
    }
    #[cfg(not(target_os = "macos"))]
    let _ = bundle;
}

// ---------------------------------------------------------------- Linux

pub fn linux_path(home: &Path) -> PathBuf {
    home.join(".local/share/applications")
        .join(format!("{LAUNCHER_ID}.desktop"))
}

pub fn linux_desktop_entry(app_exe: &Path) -> String {
    let exe = app_exe.to_string_lossy();
    let mut quoted = String::from("\"");
    for c in exe.chars() {
        if matches!(c, '"' | '`' | '$' | '\\') {
            quoted.push('\\');
        }
        quoted.push(c);
    }
    quoted.push('"');
    format!(
        "[Desktop Entry]\n\
         Type=Application\n\
         Name={LAUNCHER_NAME}\n\
         Comment=Sort your folders now\n\
         Comment[it]=Ordina subito le tue cartelle\n\
         Exec={quoted} {QUICK_SORT_FLAG}\n\
         Icon=ordo-app\n\
         Terminal=false\n\
         Categories=Utility;\n"
    )
}

pub fn linux_install(home: &Path, app_exe: &Path) -> Result<()> {
    write_file(&linux_path(home), &linux_desktop_entry(app_exe), true)
}

// ---------------------------------------------------------------- Windows

/// `%APPDATA%\Microsoft\Windows\Start Menu\Programs`.
pub fn windows_start_menu() -> Option<PathBuf> {
    std::env::var_os("APPDATA")
        .map(|a| PathBuf::from(a).join(r"Microsoft\Windows\Start Menu\Programs"))
}

pub fn windows_shortcut_in(dir: &Path) -> PathBuf {
    dir.join(format!("{LAUNCHER_NAME}.lnk"))
}

/// Creates a shortcut through the Windows Script Host (no extra dependency).
#[cfg(windows)]
pub fn windows_install_in(dir: &Path, app_exe: &Path) -> Result<()> {
    use crate::error::Error;
    std::fs::create_dir_all(dir).map_err(|e| Error::io(dir, e))?;
    let lnk = windows_shortcut_in(dir);
    let ps_quote = |p: &Path| format!("'{}'", p.to_string_lossy().replace('\'', "''"));
    let script = format!(
        "$s = (New-Object -ComObject WScript.Shell).CreateShortcut({lnk}); \
         $s.TargetPath = {exe}; $s.Arguments = '{QUICK_SORT_FLAG}'; \
         $s.IconLocation = {exe} + ',0'; $s.Description = 'Sort your folders now'; $s.Save()",
        lnk = ps_quote(&lnk),
        exe = ps_quote(app_exe),
    );
    let status = std::process::Command::new("powershell")
        .args(["-NoProfile", "-NonInteractive", "-Command", &script])
        .status()
        .map_err(|e| Error::Integration(format!("cannot run PowerShell: {e}")))?;
    if !status.success() || !lnk.is_file() {
        return Err(Error::Integration(format!(
            "cannot create the shortcut {}",
            lnk.display()
        )));
    }
    Ok(())
}

// ---------------------------------------------------------------- common

/// Where the launcher lives on this platform.
pub fn location(home: &Path) -> Option<PathBuf> {
    if cfg!(target_os = "macos") {
        Some(macos_path(home))
    } else if cfg!(windows) {
        windows_start_menu().map(|d| windows_shortcut_in(&d))
    } else {
        Some(linux_path(home))
    }
}

pub fn status(home: &Path) -> IntegrationItem {
    let path = location(home);
    IntegrationItem {
        id: "launcher".into(),
        name: format!("App “{LAUNCHER_NAME}”"),
        available: path.is_some(),
        installed: path.as_deref().is_some_and(Path::exists),
        location: path.map(|p| p.display().to_string()).unwrap_or_default(),
    }
}

pub fn install(home: &Path, app_exe: &Path) -> Result<()> {
    if cfg!(target_os = "macos") {
        macos_install(home, app_exe)?;
        register_with_launch_services(&macos_path(home));
        Ok(())
    } else if cfg!(windows) {
        #[cfg(windows)]
        if let Some(dir) = windows_start_menu() {
            windows_install_in(&dir, app_exe)?;
        }
        Ok(())
    } else {
        linux_install(home, app_exe)
    }
}

/// Whether the installed launcher starts a different app executable (the
/// app was moved or reinstalled elsewhere).
pub fn is_outdated(home: &Path, app_exe: &Path) -> bool {
    if cfg!(target_os = "macos") {
        std::fs::read_to_string(macos_path(home).join("Contents/MacOS/ordo-quick-sort"))
            .is_ok_and(|s| s != macos_script(app_exe))
    } else if cfg!(windows) {
        false
    } else {
        std::fs::read_to_string(linux_path(home)).is_ok_and(|s| s != linux_desktop_entry(app_exe))
    }
}

/// Called when the app starts: installs the launcher the first time, and
/// keeps it pointing at the current app. Returns `true` if it was installed
/// for the first time.
pub fn ensure(home: &Path, app_exe: &Path, already_offered: bool) -> Result<bool> {
    let installed = location(home).is_some_and(|p| p.exists());
    if installed {
        if is_outdated(home, app_exe) {
            install(home, app_exe)?;
        }
        Ok(false)
    } else if !already_offered {
        install(home, app_exe)?;
        Ok(true)
    } else {
        Ok(false)
    }
}

pub fn uninstall(home: &Path) -> Result<()> {
    match location(home) {
        Some(path) => remove_path(&path),
        None => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn macos_script_uses_open_for_bundles() {
        let s = macos_script(Path::new(
            "/Applications/Ordo - Settings.app/Contents/MacOS/ordo-app",
        ));
        assert!(s.contains(
            "exec /usr/bin/open -n -a '/Applications/Ordo - Settings.app' --args --quick-sort"
        ));
        let s = macos_script(Path::new("/dev/target/debug/ordo-app"));
        assert!(s.contains("'/dev/target/debug/ordo-app' --quick-sort >/dev/null 2>&1 &"));
    }

    #[test]
    fn macos_bundle_lifecycle() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path();
        // A fake app bundle with an icon.
        let app = home.join("Apps/Ordo - Settings.app");
        std::fs::create_dir_all(app.join("Contents/Resources")).unwrap();
        std::fs::write(app.join("Contents/Resources/icon.icns"), "icns").unwrap();
        let exe = app.join("Contents/MacOS/ordo-app");

        macos_install(home, &exe).unwrap();
        let bundle = macos_path(home);
        assert!(bundle.join("Contents/MacOS/ordo-quick-sort").is_file());
        assert!(bundle.join("Contents/Resources/icon.icns").is_file());
        let plist = std::fs::read_to_string(bundle.join("Contents/Info.plist")).unwrap();
        assert!(plist.contains("<string>Ordo</string>"));
        assert!(plist.contains("CFBundleIconFile"));
        #[cfg(target_os = "macos")]
        assert!(
            std::process::Command::new("plutil")
                .arg("-lint")
                .arg(bundle.join("Contents/Info.plist"))
                .status()
                .unwrap()
                .success()
        );
        remove_path(&bundle).unwrap();
        assert!(!bundle.exists());
    }

    #[cfg(unix)]
    #[test]
    fn outdated_detection() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path();
        let a = Path::new("/A/Ordo - Settings.app/Contents/MacOS/ordo-app");
        let b = Path::new("/B/Ordo - Settings.app/Contents/MacOS/ordo-app");
        if cfg!(target_os = "macos") {
            macos_install(home, a).unwrap();
        } else {
            linux_install(home, a).unwrap();
        }
        assert!(!is_outdated(home, a));
        assert!(is_outdated(home, b));
    }

    #[test]
    fn linux_entry() {
        let e = linux_desktop_entry(Path::new("/opt/My Apps/ordo-app"));
        assert!(e.contains("Name=Ordo\n"));
        assert!(e.contains("Exec=\"/opt/My Apps/ordo-app\" --quick-sort\n"));
        let tmp = tempfile::tempdir().unwrap();
        linux_install(tmp.path(), Path::new("/usr/bin/ordo-app")).unwrap();
        assert!(linux_path(tmp.path()).is_file());
    }

    #[cfg(windows)]
    #[test]
    fn windows_shortcut() {
        let tmp = tempfile::tempdir().unwrap();
        let exe = std::env::current_exe().unwrap();
        windows_install_in(tmp.path(), &exe).unwrap();
        assert!(windows_shortcut_in(tmp.path()).is_file());
    }
}
